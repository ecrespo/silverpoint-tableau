// TAB-DD-01, H-3 (TAB-T-03): from vendor/host-catalog.json, one .trex per chart a table can feed
// (trex/<slug>.trex) and the page's slim catalog (src/catalog.generated.ts). `--check` fails when a
// checked-in file differs from a fresh generation.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface Role { id: string; prop: string | null; label: string; kind: string; dataType: string; required: boolean; multiple: boolean }
interface Option { name: string; label: string; doc: string; kind: string; values?: string[]; default?: unknown }
interface Chart { slug: string; title: string; family: string; summary: string; binding: string; roles: Role[]; options: Option[] }

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ORIGIN = 'https://ecrespo.github.io';
const REPO = 'silverpoint-tableau';
/** Tableau allows up to four custom encodings on a viz extension's Marks card. */
export const MAX_ENCODINGS = 4;
/** worksheetContent, which a viz extension reads its worksheet from, arrived in Extensions API 1.12. */
export const MIN_API = '1.12';

export const releasePath = (version: string): string => `/${REPO}/v${version.split('.').slice(0, 2).join('.')}/`;
export const pageUrl = (version: string, slug: string): string => `${ORIGIN}${releasePath(version)}index.html?chart=${slug}`;

const xml = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const DATA_TYPE: Record<string, string> = { number: 'numeric', string: 'string', date: 'temporal', boolean: 'boolean' };
const ROLE_TYPES: Record<string, string[]> = {
  measure: ['continuous-measure', 'discrete-measure'],
  dimension: ['discrete-dimension'],
  temporal: ['continuous-dimension', 'discrete-dimension'],
};

export function trexFor(chart: Chart, version: string): string {
  const encodings = chart.roles.map((role) => {
    const types = ROLE_TYPES[role.kind] ?? [];
    return [
      `    <encoding id="${xml(role.id)}">`,
      `      <display-name>${xml(role.label)}</display-name>`,
      ...(DATA_TYPE[role.dataType] ? ['      <data-spec>', `        <data-type>${DATA_TYPE[role.dataType]}</data-type>`, '      </data-spec>'] : []),
      ...(types.length > 0 ? ['      <role-spec>', ...types.map((t) => `        <role-type>${t}</role-type>`), '      </role-spec>'] : []),
      ...(role.multiple ? [] : ['      <fields max-count="1"/>']),
      `      <tooltip>${xml(`${role.label}: ${role.multiple ? 'one or more fields' : 'one field'}${role.required ? '' : ' (optional)'}`)}</tooltip>`,
      '    </encoding>',
    ].join('\n');
  });
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<manifest manifest-version="0.1" xmlns="http://www.tableau.com/xml/extension_manifest">',
    `  <worksheet-extension id="to.seraph.silverpoint.${xml(chart.slug)}" extension-version="${xml(version)}">`,
    '    <default-locale>en_US</default-locale>',
    '    <name resource-id="name"/>',
    `    <description>${xml(chart.summary || chart.title)}</description>`,
    `    <author name="Ernesto Crespo" email="ecrespo@gmail.com" organization="silverpoint" website="https://github.com/ecrespo/${REPO}"/>`,
    `    <min-api-version>${MIN_API}</min-api-version>`,
    '    <source-location>',
    `      <url>${xml(pageUrl(version, chart.slug))}</url>`,
    '    </source-location>',
    '    <icon/>',
    ...encodings,
    '  </worksheet-extension>',
    '  <resources>',
    '    <resource id="name">',
    `      <text locale="en_US">${xml(`Silverpoint ${chart.title}`)}</text>`,
    '    </resource>',
    '  </resources>',
    '</manifest>',
    '',
  ].join('\n');
}

export function catalogModule(catalog: { version: string; appearance: unknown; common: Option[]; charts: Chart[] }, charts: Chart[]): string {
  const slim = Object.fromEntries(charts.map((c) => [c.slug, { slug: c.slug, title: c.title, roles: c.roles, options: c.options }]));
  return [
    `// Generated by scripts/make-trex.ts from host catalog ${catalog.version}. Do not edit (H-3).`,
    "import type { CatalogChart, CatalogOption, CatalogAppearance } from './catalog-types';",
    '',
    `export const ENGINE_VERSION = ${JSON.stringify(catalog.version)};`,
    `export const APPEARANCE: CatalogAppearance = ${JSON.stringify(catalog.appearance, null, 2)};`,
    `export const COMMON: readonly CatalogOption[] = ${JSON.stringify(catalog.common, null, 2)};`,
    `export const CHARTS: Readonly<Record<string, CatalogChart>> = ${JSON.stringify(slim, null, 2)};`,
    '',
  ].join('\n');
}

function outputs(): Map<string, string> {
  const catalog = JSON.parse(readFileSync(`${ROOT}vendor/host-catalog.json`, 'utf8'));
  const { version } = JSON.parse(readFileSync(`${ROOT}package.json`, 'utf8'));
  const charts = (catalog.charts as Chart[]).filter((c) => c.binding !== 'none' && c.roles.length <= MAX_ENCODINGS);
  const files = new Map<string, string>();
  for (const chart of charts) files.set(`trex/${chart.slug}.trex`, trexFor(chart, version));
  files.set('src/catalog.generated.ts', catalogModule(catalog, charts));
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = outputs();
  if (process.argv.includes('--check')) {
    const present = readdirSync(`${ROOT}trex`).map((f) => `trex/${f}`);
    const stale = [...files].filter(([path, text]) => { try { return readFileSync(`${ROOT}${path}`, 'utf8') !== text; } catch { return true; } }).map(([p]) => p);
    const extra = present.filter((p) => !files.has(p));
    if (stale.length + extra.length > 0) {
      console.log(`stale: ${[...stale, ...extra].join(', ')} — run \`npm run generate\``);
      process.exit(1);
    }
    console.log(`manifests current (${files.size - 1} charts)`);
  } else {
    rmSync(`${ROOT}trex`, { recursive: true, force: true });
    mkdirSync(`${ROOT}trex`);
    for (const [path, text] of files) writeFileSync(`${ROOT}${path}`, text);
    console.log(`wrote ${files.size - 1} manifests and src/catalog.generated.ts`);
  }
}
